package uk.org.cricbase.DTOs;

/**
 *
 * @author Benjamin
 */
public class GroundSummary {
    private long id;
    private String name;
    private String city;
    
    public GroundSummary() {
        
    }

    public long getId() {
        return id;
    }

    public void setId(long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCity() {
        return city;
    }

    public void setCity(String city) {
        this.city = city;
    }
    
    
    
}
